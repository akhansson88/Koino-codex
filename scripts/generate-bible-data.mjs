import { gzipSync } from "node:zlib";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = path.join(projectRoot, "features", ".generated");
const sources = {
  "cross-references.ts": {
    exportName: "compressedCrossReferences",
    path: "assets/bible/cross-references/cross_references.json",
  },
  "kjv-verses.ts": {
    exportName: "compressedKjvVerses",
    path: "assets/bible/kjv-verses-1769.json",
  },
  "reformationsbibeln-verses.ts": {
    exportName: "compressedReformationsbibelnVerses",
    path: "assets/bible/reformationsbibeln.json",
  },
};

await mkdir(outputDirectory, { recursive: true });

for (const [fileName, source] of Object.entries(sources)) {
  const contents = await readFile(path.join(projectRoot, source.path));
  const encoded = gzipSync(contents, { level: 9 }).toString("base64");
  await writeFile(
    path.join(outputDirectory, fileName),
    `// Generated by scripts/generate-bible-data.mjs. Do not edit.\nexport const ${source.exportName} = ${JSON.stringify(encoded)};\n`,
    "utf8",
  );
}

const crossReferenceData = JSON.parse(
  await readFile(path.join(projectRoot, sources["cross-references.ts"].path), "utf8"),
);
await writeFile(
  path.join(outputDirectory, "cross-reference-sources.ts"),
  `// Generated by scripts/generate-bible-data.mjs. Do not edit.\nexport const crossReferenceSources = ${JSON.stringify(Object.keys(crossReferenceData.references ?? {}))};\n`,
  "utf8",
);
