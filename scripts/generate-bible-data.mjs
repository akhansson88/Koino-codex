import { gzipSync } from "node:zlib";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputDirectory = path.join(projectRoot, "features", ".generated");
const sources = {
  compressedCrossReferences: "assets/bible/cross-references/cross_references.json",
  compressedKjvVerses: "assets/bible/kjv-verses-1769.json",
  compressedReformationsbibelnVerses: "assets/bible/reformationsbibeln.json",
  compressedSv1917Verses: "assets/bible/sv1917-verses.json",
};

const exports = [];
for (const [name, relativePath] of Object.entries(sources)) {
  const contents = await readFile(path.join(projectRoot, relativePath));
  const encoded = gzipSync(contents, { level: 9 }).toString("base64");
  exports.push(`export const ${name} = ${JSON.stringify(encoded)};`);
}

await mkdir(outputDirectory, { recursive: true });
await writeFile(
  path.join(outputDirectory, "bible-data.ts"),
  `// Generated by scripts/generate-bible-data.mjs. Do not edit.\n${exports.join("\n")}\n`,
  "utf8",
);
