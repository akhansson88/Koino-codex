export function readDictionary(filePath) {
  if (!fs.existsSync(filePath)) return undefined;
  const source = ts.createSourceFile(filePath, fs.readFileSync(filePath, "utf8"), ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  let result;
  function visit(node) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer) {
      let initializer = node.initializer;
      while (ts.isAsExpression(initializer) || ts.isSatisfiesExpression(initializer)) initializer = initializer.expression;
      if (ts.isObjectLiteralExpression(initializer)) {
        const entries = [];
        for (const property of initializer.properties) {
          if (!ts.isPropertyAssignment(property)) continue;
          const key = ts.isStringLiteral(property.name) || ts.isNoSubstitutionTemplateLiteral(property.name)
            ? property.name.text
            : property.name.getText(source);
          const value = property.initializer;
          if (ts.isStringLiteral(value) || ts.isNoSubstitutionTemplateLiteral(value)) {
            entries.push([key, value.text]);
          } else {
            throw new Error(`${filePath}: value for "${key}" is not a string literal`);
          }
        }
        result = entries;
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (!result) throw new Error(`Could not read a translation dictionary from ${filePath}`);
  const dictionary = new Map();
  for (const [key, value] of result) {
    if (dictionary.has(key)) throw new Error(`${filePath}: duplicate key "${key}"`);
    dictionary.set(key, value);
  }
  return dictionary;
}

export function readJson(filePath, fallback) {
  if (!fs.existsSync(filePath)) return fallback;
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

export function readReviewed(language) {
  return readJson(path.join(reviewedDir, `${language}.json`), {});
}

export function writeDictionary(language, entries) {
  const { file, exportName } = languageFiles[language];
  const lines = [
    "// Generated by npm run i18n:sync. Edit ui/translations/en.ts for new copy,",
    "// or add a reviewed override in ui/translations/reviewed/<language>.json.",
    'import { type TranslationDictionary } from "@/ui/translations/types";',
    "",
    `export const ${exportName}: TranslationDictionary = {`,
  ];
  for (const [key, value] of entries) {
    lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  }
  lines.push("};", "");
  fs.writeFileSync(path.join(translationsDir, file), lines.join("\n"), "utf8");
}

export function sourceHash(value) {
  return crypto.createHash("sha1").update(value).digest("hex").slice(0, 12);
}

export function placeholders(value) {
  return [...value.matchAll(/\{([A-Za-z0-9_]+)\}/g)].map((match) => match[1]).sort();
}

const brandTerms = [
  "Svenska Folkbibeln 2015",
  "Reformationsbibeln 2026",
  "Reformationsbibeln",
  "KOINO Dev",
  "KOINO",
  "NKJV",
  "KJV",
  "SFB15",
  "SRB26",
  "%LINK%",
  "%EMAIL%",
];

const tokenPattern = /⟦(\d+)⟧/g;

function protect(text) {
  const saved = [];
  let output = text;
  for (const term of brandTerms) {
    output = output.replaceAll(term, () => {
      const index = saved.push(term) - 1;
      return `⟦${index}⟧`;
    });
  }
  output = output.replace(/\{([A-Za-z0-9_]+)\}/g, (_, name) => {
    const index = saved.push(`{${name}}`) - 1;
    return `⟦${index}⟧`;
  });
  return { text: output, saved };
}

function restore(text, saved) {
  return text.replace(tokenPattern, (token, index) => saved[Number(index)] ?? token);
}

function decodeEntities(value) {
  return value
    .replaceAll("&quot;", '"')
    .replaceAll("&#39;", "'")
    .replaceAll("&amp;", "&")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replace(/&#(\d+);/g, (_, code) => String.fromCodePoint(Number(code)));
}

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

function splitWhitespace(value) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return {
    leading,
    trailing,
    core: value.slice(leading.length, value.length - trailing.length),
  };
}

async function requestBatch(texts, target) {
  const params = new URLSearchParams();
  params.set("client", "gtx");
  params.set("sl", "en");
  params.set("tl", googleCodes[target]);
  for (const text of texts) params.append("q", text);
  const response = await fetch(`https://translate.googleapis.com/translate_a/t?${params.toString()}`, {
    signal: AbortSignal.timeout(30000),
  });
  if (!response.ok) throw new Error(`translate HTTP ${response.status}`);
  const data = await response.json();
  if (!Array.isArray(data) || data.length !== texts.length) throw new Error("unexpected batch response");
  return data.map((value) => (typeof value === "string" ? decodeEntities(value) : ""));
}

async function translateOne(text, target) {
  const url = "https://translate.googleapis.com/translate_a/single"
    + `?client=gtx&sl=en&tl=${encodeURIComponent(googleCodes[target])}&dt=t&q=${encodeURIComponent(text)}`;
  const response = await fetch(url, { signal: AbortSignal.timeout(20000) });
  if (!response.ok) throw new Error(`translate HTTP ${response.status}`);
  const data = await response.json();
  if (!Array.isArray(data) || !Array.isArray(data[0])) throw new Error("unexpected translate response");
  return decodeEntities(data[0].map((part) => (Array.isArray(part) ? part[0] ?? "" : "")).join(""));
}

async function withRetries(work, attempts = 5) {
  let lastError;
  for (let attempt = 0; attempt < attempts; attempt += 1) {
    try {
      return await work();
    } catch (error) {
      lastError = error;
    }
    await sleep(350 * 2 ** attempt + Math.floor(Math.random() * 250));
  }
  throw lastError ?? new Error("translation failed");
}

function batchesFor(items, target) {
  const batches = [];
  let current = [];
  let length = 0;
  for (const item of items) {
    const cost = item.text.length + 8;
    if (current.length && (current.length >= 40 || length + cost > 6000)) {
      batches.push(current);
      current = [];
      length = 0;
    }
    current.push(item);
    length += cost;
  }
  if (current.length) batches.push(current);
  return batches;
}

/**
 * Translate a list of English UI strings. Placeholders and brand names travel
 * as tokens, so "{count} ribbons" can never lose or rename its placeholder.
 */
export async function translateTexts(values, target) {
  if (target === "en") return [...values];
  const results = new Array(values.length);
  const work = values.map((value, index) => {
    const whitespace = splitWhitespace(value);
    if (!/[A-Za-zÀ-ÖØ-öø-ÿ]/.test(whitespace.core)) return { index, value, skip: true };
    return { index, value, ...whitespace, ...protect(whitespace.core) };
  });

  const batches = batchesFor(work.filter((item) => !item.skip), target);
  for (const batch of batches) {
    try {
      const translated = await withRetries(() => requestBatch(batch.map((item) => item.text), target));
      batch.forEach((item, position) => {
        results[item.index] = restore(translated[position] ?? "", item.saved).trim();
      });
    } catch {
      await mapWithConcurrency(batch, 6, async (item) => {
        try {
          const translated = await withRetries(() => translateOne(item.text, target));
          results[item.index] = restore(translated, item.saved).trim();
        } catch {
          results[item.index] = "";
        }
      });
    }
  }

  return values.map((value, index) => {
    if (results[index] === undefined || results[index] === null) return value;
    const source = work[index];
    if (source.skip) return value;
    const expected = placeholders(value);
    const actual = placeholders(results[index]);
    if (!results[index].trim() || JSON.stringify(expected) !== JSON.stringify(actual)) {
      return value;
    }
    return `${source.leading}${results[index].trim()}${source.trailing}`;
  });
}

export async function translateText(value, target) {
  if (!/[A-Za-zÀ-ÖØ-öø-ÿ]/.test(value) || target === "en") return value;
  return (await translateTexts([value], target))[0];
}


export async function mapWithConcurrency(items, concurrency, worker) {
  const results = new Array(items.length);
  let cursor = 0;
  const runners = Array.from({ length: Math.min(concurrency, items.length) }, async () => {
    while (cursor < items.length) {
      const index = cursor;
      cursor += 1;
      results[index] = await worker(items[index], index);
    }
  });
  await Promise.all(runners);
  return results;
}


